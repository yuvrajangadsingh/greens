  if [[ -f "$MIRROR_DIR/.git/config" ]] && [[ ! -O "$MIRROR_DIR/.git/config" ]]; then
    echo "ERROR: $MIRROR_DIR/.git/config is not owned by the current user. Refusing." >&2
    exit 1
  fi
  if git -C "$MIRROR_DIR" remote get-url origin >/dev/null 2>&1; then
    # ALL advertised refs (notes/custom included) — legacy history reachable
    # only through a stray ref must still trip the gate.
    if ! git -C "$MIRROR_DIR" fetch --prune origin "+refs/heads/*:refs/remotes/origin/*" "+refs/*:refs/greens-remote-scan/*" --quiet 2>/dev/null; then
      # Local evidence of dashboard history + no proof of privacy refuses
      # immediately; a CLEAN local result is likewise not authoritative while
      # the remote is unreachable.
      if [[ "$(scan_repo_readme_state "$MIRROR_DIR")" == "generated" ]] && \
         [[ "$(mirror_visibility)" != "private" ]]; then
        legacy_refuse
      fi
      log "ERROR: couldn't refresh the mirror from origin for the privacy check."
      log "A stale local clone can't prove the remote is clean — refusing to sync."
      log "Fix access to the mirror remote and re-run."
      exit 1
    fi
  fi
  legacy_state="$(scan_repo_readme_state "$MIRROR_DIR")"
  if [[ "$legacy_state" == "generated" ]]; then
    # The dashboard README (work repo names) is allowed to exist ONLY where
    # nobody but the owner can read it: a positively verified PRIVATE GitHub
    # mirror. Public or unverifiable (gh missing/unauthenticated, non-GitHub
    # remote) trips the refusal.
    if [[ "$(mirror_visibility)" == "private" ]]; then
      log "Mirror is verified private — dashboard README history is OK here."
    else
      legacy_refuse
    fi
  elif [[ "$legacy_state" == "foreign" ]]; then
    log "NOTE: the mirror has a README greens didn't generate; it is left alone."
  fi
fi

