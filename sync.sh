        [[ "$url" != "$normalized" ]] && log "  WARN: $repodir uses $url; normalizing to $normalized"
      fi
      ;;
  esac
  [[ -z "$normalized" ]] && continue
  url="$normalized"

  remote_repo="$(basename "$url")"
  printf "%s %s\n" "$remote_repo" "$url" >> "$tmp_pairs"
