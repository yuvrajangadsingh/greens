# Per-fetch hard timeout so one stuck repo can't wedge the whole sync.
# Prefer GNU coreutils, then macOS-native timeout, else a Bash-native fallback
# that kills the whole process group.
GREENS_FETCH_TIMEOUT="${GREENS_FETCH_TIMEOUT:-120}"
if command -v gtimeout >/dev/null 2>&1; then
  TIMEOUT_CMD=(gtimeout --kill-after=10 "$GREENS_FETCH_TIMEOUT")
elif command -v timeout >/dev/null 2>&1; then
  TIMEOUT_CMD=(timeout --kill-after=10 "$GREENS_FETCH_TIMEOUT")
elif command -v perl >/dev/null 2>&1; then
  # perl setpgrp makes the exec'd command a process group leader, so
  # kill -TERM -$pid terminates git AND its ssh child. If setpgrp is a
  # no-op on this platform, the negative-pid kill falls back to the
  # positive-pid form so at least git itself gets terminated.
  run_with_timeout() {
    local seconds="$1"; shift
    perl -e 'setpgrp 0,0; exec @ARGV or die "exec failed: $!"' "$@" &
    local pid=$!
    (
      sleep "$seconds"
      kill -TERM -"$pid" 2>/dev/null || kill -TERM "$pid" 2>/dev/null
      sleep 10
      kill -KILL -"$pid" 2>/dev/null || kill -KILL "$pid" 2>/dev/null
    ) &
    local watcher=$!
    wait "$pid" 2>/dev/null
    local rc=$?
    kill "$watcher" 2>/dev/null
    wait "$watcher" 2>/dev/null
    return "$rc"
  }
  TIMEOUT_CMD=(run_with_timeout "$GREENS_FETCH_TIMEOUT")
else
  log "WARN: no timeout or perl available; fetches won't be bounded."
  TIMEOUT_CMD=()
fi

repo_total="$(wc -l < "$tmp_sorted" | tr -d " ")"
log ""
log "Step 2/5: Caching $repo_total repos (read-only copies — your code stays untouched)"

failures=0
fetched_ok=0
while read -r remote_repo url; do
  [[ -z "$remote_repo" ]] && continue
  bare="$CACHE_DIR/$remote_repo"

  if [[ ! -d "$bare" ]]; then
    log "Cloning $remote_repo"
    # ${arr[@]+...} guards the empty-array case — bash 3.2 + set -u aborts on
    # plain "${arr[@]}" when the array has no elements.
    if ! err="$(${TIMEOUT_CMD[@]+"${TIMEOUT_CMD[@]}"} git clone --bare --filter=blob:none --no-tags "$url" "$bare" 2>&1)"; then
      log "WARN: clone failed for $remote_repo: $(echo "$err" | tail -n 3 | tr '\n' ' ')"
      failures=$((failures + 1))
      rm -rf "$bare" >/dev/null 2>&1 || true
      continue
    fi
  fi

  git --git-dir="$bare" remote set-url origin "$url" >/dev/null 2>&1 || true

  if ! git --git-dir="$bare" config --get-all remote.origin.fetch >/dev/null 2>&1; then
    git --git-dir="$bare" config remote.origin.fetch "+refs/heads/*:refs/heads/*"
  fi

  log "Fetching $remote_repo"
  if ! err="$(${TIMEOUT_CMD[@]+"${TIMEOUT_CMD[@]}"} git --git-dir="$bare" fetch --prune --no-tags --filter=blob:none origin "+refs/heads/*:refs/heads/*" 2>&1)"; then
    log "WARN: fetch failed for $remote_repo: $(echo "$err" | tail -n 3 | tr '\n' ' ')"
    failures=$((failures + 1))
    continue
  fi
  fetched_ok=$((fetched_ok + 1))
done < "$tmp_sorted"

if [[ "$failures" -gt 0 ]]; then
  log "WARN: $failures repos failed to fetch"
fi

if [[ "$fetched_ok" -eq 0 ]]; then
  log "ERROR: all fetches failed; not proceeding with stale data."
  exit 1
fi

# ─────────────────────────────────────────────────────────────────────────────
# Collect unique timestamps
# ─────────────────────────────────────────────────────────────────────────────

tmp_all_data="/tmp/greens_all.txt"
tmp_origin_ts="/tmp/greens_origin_ts.txt"
tmp_mirror_ts="/tmp/greens_mirror_ts.txt"
tmp_missing_ts="/tmp/greens_missing_ts.txt"
tmp_missing_data="/tmp/greens_missing_data.txt"

> "$tmp_all_data"

log ""
log "Step 3/5: Scanning commits across all branches (emails: $EMAILS)"
log "  (Checks every branch — feature, hotfix, etc. No double-counting after merge)"

# Collect git commits (with or without messages based on COPY_MESSAGES)
for bare in "$CACHE_DIR"/*.git; do
  [[ -d "$bare" ]] || continue

  origin_url="$(git --git-dir="$bare" remote get-url origin 2>/dev/null || true)"
  case "$origin_url" in
    "$REMOTE_PREFIX"*) ;;
    *) continue ;;
  esac

  # --fixed-strings: the email is matched literally, not as a regex ("a@x.com"
  # as a regex also matches "a@xX.com" — a colleague's activity could leak in).
  # --regexp-ignore-case: git emails are case-insensitive in practice.
  for email in ${EMAIL_ARRAY[@]+"${EMAIL_ARRAY[@]}"}; do
    if [[ "$COPY_MESSAGES" == "1" ]]; then
      git --git-dir="$bare" log --all --since="$SINCE" --fixed-strings --regexp-ignore-case --author="<$email>" --format="%ai	%s" 2>/dev/null || true
    else
      git --git-dir="$bare" log --all --since="$SINCE" --fixed-strings --regexp-ignore-case --author="<$email>" --format="%ai" 2>/dev/null || true
    fi
  done
done >> "$tmp_all_data"

# Fetch GitHub activity (PRs, reviews, issues)
if [[ "$ACTIVITY_TYPES" == *"reviews"* ]]; then
  log "NOTE: 'reviews' tracks PR updatedAt (not review time) and mints unstable squares; it's no longer a default. Remove it from ACTIVITY_TYPES to silence this."
fi
if [[ "$ACTIVITY_TYPES" != "commits" ]] && [[ -n "$GITHUB_USERNAME" ]]; then
  since_date="${SINCE%% *}"  # Extract date part only (YYYY-MM-DD)
  if [[ -z "$GITHUB_ORG" ]]; then
    GITHUB_ORG="$(echo "$REMOTE_PREFIX" | sed 's|.*[:/]\([^/]*\)/$|\1|')"
  fi
  log "Fetching GitHub activity (PRs, reviews, issues) since $since_date..."

  if [[ "$COPY_MESSAGES" == "1" ]]; then
    # Fetch with titles (timestamp<TAB>message format)
    fetch_github_activity_with_messages "$since_date" "$GITHUB_ORG" >> "$tmp_all_data"
  else
    # Fetch timestamps only
    fetch_github_activity "$since_date" "$GITHUB_ORG" >> "$tmp_all_data"
  fi

  total_count="$(wc -l < "$tmp_all_data" | tr -d " ")"
  log "Total entries (commits + GitHub activity): $total_count"
fi

# Deduplicate and extract timestamps for comparison
if [[ "$COPY_MESSAGES" == "1" ]]; then
  LC_ALL=C sort -t$'\t' -k1,1 -u "$tmp_all_data" > "$tmp_all_data.sorted"
  mv "$tmp_all_data.sorted" "$tmp_all_data"
  cut -f1 "$tmp_all_data" | LC_ALL=C sort -u > "$tmp_origin_ts"
else
  LC_ALL=C sort -u "$tmp_all_data" > "$tmp_origin_ts"
fi

{ git -C "$MIRROR_DIR" log --format="%ai" 2>/dev/null || true; } | LC_ALL=C sort -u > "$tmp_mirror_ts"
comm -23 "$tmp_origin_ts" "$tmp_mirror_ts" > "$tmp_missing_ts"

# Build missing data file (with messages if enabled)
if [[ "$COPY_MESSAGES" == "1" ]]; then
  > "$tmp_missing_data"
  while IFS= read -r ts; do
    [[ -z "$ts" ]] && continue
    msg="$(grep "^${ts}	" "$tmp_all_data" 2>/dev/null | head -1 | cut -f2-)"
    [[ -z "$msg" ]] && msg="sync"
    printf '%s\t%s\n' "$ts" "$msg" >> "$tmp_missing_data"
  done < "$tmp_missing_ts"
fi

origin_count="$(wc -l < "$tmp_origin_ts" | tr -d " ")"
mirror_count="$(wc -l < "$tmp_mirror_ts" | tr -d " ")"
missing_count="$(wc -l < "$tmp_missing_ts" | tr -d " ")"

log "Origin timestamps: $origin_count"
log "Mirror timestamps: $mirror_count"
log "Missing (to sync): $missing_count"

# ─────────────────────────────────────────────────────────────────────────────
# Add missing commits to mirror
# ─────────────────────────────────────────────────────────────────────────────

log ""
log "Step 4/5: Creating mirror commits (these show up as green squares on GitHub)"

# Every synthetic commit gets the mirror identity pinned via BOTH environment
# and -c overrides. MIRROR_EMAIL is guaranteed non-empty (hard-fail above);
# never let the machine's git identity leak into the mirror.

if [[ "$missing_count" -gt 0 ]]; then
  log "Adding $missing_count new commits to mirror..."
  cd "$MIRROR_DIR"

  if [[ "$COPY_MESSAGES" == "1" ]]; then
    while IFS=$'\t' read -r ts msg; do
      [[ -z "$ts" ]] && continue
      [[ -z "$msg" ]] && msg="sync"
      GIT_AUTHOR_DATE="$ts" GIT_COMMITTER_DATE="$ts" \
      GIT_AUTHOR_NAME="$MIRROR_NAME" GIT_AUTHOR_EMAIL="$MIRROR_EMAIL" \
      GIT_COMMITTER_NAME="$MIRROR_NAME" GIT_COMMITTER_EMAIL="$MIRROR_EMAIL" \
        git -c user.name="$MIRROR_NAME" -c user.email="$MIRROR_EMAIL" \
          commit --allow-empty -m "$msg" --quiet
    done < "$tmp_missing_data"
  else
    while IFS= read -r ts; do
      [[ -z "$ts" ]] && continue
      GIT_AUTHOR_DATE="$ts" GIT_COMMITTER_DATE="$ts" \
      GIT_AUTHOR_NAME="$MIRROR_NAME" GIT_AUTHOR_EMAIL="$MIRROR_EMAIL" \
      GIT_COMMITTER_NAME="$MIRROR_NAME" GIT_COMMITTER_EMAIL="$MIRROR_EMAIL" \
        git -c user.name="$MIRROR_NAME" -c user.email="$MIRROR_EMAIL" \
          commit --allow-empty -m "sync" --quiet
    done < "$tmp_missing_ts"
  fi
  log "Mirror commits added."
else
  log "Mirror already up to date."
fi

# ─────────────────────────────────────────────────────────────────────────────
# Dashboard README — PRIVATE mirrors only
#
# The dashboard lists work repo NAMES with per-repo commit counts. That is a
# feature when only the owner can read it, and a leak everywhere else. It is
# written ONLY when the mirror is positively verified PRIVATE on GitHub
# (cached gh check, one API call per run). Public or unverifiable mirrors —
# including non-GitHub remotes — never get the repo-names table.
# Same format as v1.8.1, so the ownership signature detection recognizes its
# own output; the visibility check is what keeps a fresh dashboard from
# tripping the privacy gate on the next run.
# ─────────────────────────────────────────────────────────────────────────────

if [[ "$(mirror_visibility)" == "private" ]]; then
  log ""
  log "Updating dashboard README (mirror is verified private)"

  STATUS_FILE="$MIRROR_DIR/README.md"
  final_mirror_count="$(git -C "$MIRROR_DIR" log --format="%ai" 2>/dev/null | LC_ALL=C sort -u | wc -l | tr -d " ")"

  # Collect per-repo stats
  tmp_repo_stats="$(mktemp)"
  tmp_dates="$(mktemp)"
  for bare in "$CACHE_DIR"/*.git; do
    [[ -d "$bare" ]] || continue
    repo_name="$(basename "$bare" .git)"

    origin_url="$(git --git-dir="$bare" remote get-url origin 2>/dev/null || true)"
    case "$origin_url" in
      "$REMOTE_PREFIX"*) ;;
      *) continue ;;
    esac

    repo_commits=0
    for email in ${EMAIL_ARRAY[@]+"${EMAIL_ARRAY[@]}"}; do
      count="$(git --git-dir="$bare" log --all --since="$SINCE" --fixed-strings --regexp-ignore-case --author="<$email>" --format="%H" 2>/dev/null | wc -l | tr -d " ")"
      repo_commits=$((repo_commits + count))
      git --git-dir="$bare" log --all --since="$SINCE" --fixed-strings --regexp-ignore-case --author="<$email>" --format="%ad" --date=short 2>/dev/null >> "$tmp_dates" || true
    done

    if [[ "$repo_commits" -gt 0 ]]; then
      printf "%d|%s\n" "$repo_commits" "$repo_name" >> "$tmp_repo_stats"
    fi
  done

  sorted_repos="$(sort -t'|' -k1 -nr "$tmp_repo_stats")"
  total_commits="$(echo "$sorted_repos" | awk -F'|' '{sum+=$1} END {print sum}')"
  total_commits="${total_commits:-0}"

  # Build repo breakdown
  repo_breakdown=""
  while IFS='|' read -r count name; do
    [[ -z "$count" ]] && continue
    if [[ "$total_commits" -gt 0 ]]; then
      percentage=$((count * 100 / total_commits))
    else
      percentage=0
    fi
    bar_length=$((percentage / 5))
    bar=""
    for ((i=0; i<bar_length; i++)); do bar+="█"; done
    for ((i=bar_length; i<20; i++)); do bar+="░"; done
    repo_breakdown+="| \`$name\` | $count | $bar $percentage% |
"
  done <<< "$sorted_repos"

  total_active_days="$(LC_ALL=C sort -u "$tmp_dates" | wc -l | tr -d " ")"
  repo_count="$(echo "$sorted_repos" | grep -c '|' || echo 0)"

  mirror_mode="timestamps only"
  [[ "$COPY_MESSAGES" == "1" ]] && mirror_mode="timestamps + messages"

  cat > "$STATUS_FILE" << EOF
# Work Contributions Mirror

This repository mirrors commit ${mirror_mode} from private work repositories to maintain GitHub contribution visibility.

---

## Overview

| Metric | Value |
|:-------|------:|
| Total Commits | **$total_commits** |
| Active Days | **$total_active_days** |
| Repos Tracked | **$repo_count** |
| Since | $SINCE |

---

## Repository Breakdown

| Repository | Commits | Distribution |
|:-----------|--------:|:-------------|
$repo_breakdown
---

## Sync Info

| | |
|:--|:--|
| Last Sync | \`$(timestamp)\` |
| Mirror Commits | $final_mirror_count |
| Added This Run | $missing_count |
| Status | $(if [[ "$missing_count" -gt 0 ]]; then echo "✓ Synced"; else echo "✓ Up to date"; fi) |

---

<sub>Generated by [greens](https://github.com/yuvrajangadsingh/greens)</sub>
EOF

  rm -f "$tmp_repo_stats" "$tmp_dates" 2>/dev/null || true

  # Commit the dashboard only when this run actually synced something.
  # The status commit uses a NEUTRAL non-account identity so it never paints
  # a contribution square (author date would be "now" — a phantom day).
  cd "$MIRROR_DIR"
  git add README.md
  if ! git diff --cached --quiet && [[ "$missing_count" -gt 0 ]]; then
    GIT_AUTHOR_NAME="greens-status" GIT_AUTHOR_EMAIL="status@greens.local" \
    GIT_COMMITTER_NAME="greens-status" GIT_COMMITTER_EMAIL="status@greens.local" \
      git -c user.name="greens-status" -c user.email="status@greens.local" \
        commit -m "Update sync status" --quiet
    log "Dashboard README updated."
  fi
else
  log ""
  log "Mirror is not verified private ($(mirror_visibility)) — the repo-names dashboard README is not written."
fi

# ─────────────────────────────────────────────────────────────────────────────
# Push
# ─────────────────────────────────────────────────────────────────────────────

log ""
log "Step 5/5: Pushing to GitHub (making your contribution graph green)"

if ! git -C "$MIRROR_DIR" rev-parse --verify --quiet HEAD >/dev/null 2>&1; then
  # Brand-new mirror with zero activity found: nothing to push yet.
  log "Mirror has no commits yet (no matching activity found). Nothing to push."
  if [[ "${GREENS_PUSH_FORCE:-0}" == "1" ]]; then
    log "WARN: remote history was NOT overwritten — there are no local commits to push."
  fi
else
  do_push() {
    if [[ "${GREENS_PUSH_FORCE:-0}" == "1" ]]; then
      git -C "$MIRROR_DIR" push --force origin HEAD 2>&1
    else
      git -C "$MIRROR_DIR" push origin HEAD 2>&1
    fi
  }
  push_output=""
  if push_output="$(do_push)"; then
    log "Mirror pushed."
  else
    log "ERROR: Push to mirror repo failed."
    log "$push_output"
    log ""
    log "Your commits were created locally but won't show on GitHub until push works."
    log "Fix: re-run 'greens --setup' to reconfigure push access,"
    log "  or manually: git -C \"$MIRROR_DIR\" remote set-url origin https://<token>@github.com/<user>/<repo>.git"
    # No success stamp on failure — the next scheduled run must retry instead
    # of silently skipping the day.
    exit 1
  fi
  log "Mirror tip: $(git -C "$MIRROR_DIR" log -1 --format='%h %ai %s' 2>/dev/null || true)"
fi

# Stamp success atomically, and only after the push (or up-to-date) succeeded.
echo "$today" > "$SUCCESS_STAMP_FILE.tmp.$$"
mv "$SUCCESS_STAMP_FILE.tmp.$$" "$SUCCESS_STAMP_FILE"
log "Done."
